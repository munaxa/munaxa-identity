import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import type {
  DeliveryResult,
  NotificationMessage,
  NotificationTransportPort,
} from '@munaxa/interfaces';
import type { IdentityEnvironment } from '@identity/config';

/**
 * Email delivery: the port, and the transports this repository ships.
 *
 * The port is Platform's `NotificationTransportPort`, unchanged — one `send` that returns whether
 * the message was accepted and whether a failure is worth retrying. Identity adds no provider SDK
 * and no provider credentials. A real provider (on AWS, the SES v2 `SendEmail` API called with the
 * ECS task role, never an SMTP user with a long-lived password) is one more class implementing this
 * interface; see `docs/runbooks/password-recovery.md`.
 *
 * What ships today:
 *
 * - **none** — there is no transport. Recovery reports itself unavailable and creates no tokens.
 * - **outbox** — writes each message to a JSON file in a directory. For development and tests: a
 *   developer can follow a reset link without a mail server, and nothing about the message reaches
 *   a log. The configuration refuses it in production.
 *
 * A transport never logs a message body or a recipient. The reset link *is* the credential, so a
 * log line holding it is a log line that can take over an account.
 */
export interface EmailTransport extends NotificationTransportPort {
  readonly channel: 'email';
  /** Whether this transport may carry live credentials in a production deployment. */
  readonly productionGrade: boolean;
}

/** Writes one file per message. Development only; refused in production by configuration. */
export class OutboxEmailTransport implements EmailTransport {
  public readonly channel = 'email' as const;
  public readonly name = 'outbox';
  public readonly productionGrade = false;

  public constructor(private readonly directory: string) {}

  public async send(message: NotificationMessage): Promise<DeliveryResult> {
    try {
      await mkdir(this.directory, { recursive: true, mode: 0o700 });
      // The id is generated by this service, never by the request, so it is safe as a file name.
      const file = join(this.directory, `${message.id.replace(/[^A-Za-z0-9_-]/g, '_')}.json`);
      await writeFile(file, JSON.stringify(message, null, 2), { mode: 0o600, flag: 'wx' });
      return { delivered: true, providerMessageId: message.id };
    } catch (error) {
      return { delivered: false, error: (error as Error).name, retryable: false };
    }
  }

  public healthy(): Promise<boolean> {
    return Promise.resolve(true);
  }
}

/** Collects messages in memory. For tests that need to read the link a user would have received. */
export class MemoryEmailTransport implements EmailTransport {
  public readonly channel = 'email' as const;
  public readonly name = 'memory';
  public readonly productionGrade = false;
  public readonly sent: NotificationMessage[] = [];
  /** Fail the next N sends. */
  public failures = 0;
  public retryable = true;

  public send(message: NotificationMessage): Promise<DeliveryResult> {
    if (this.failures > 0) {
      this.failures -= 1;
      return Promise.resolve({ delivered: false, error: 'simulated', retryable: this.retryable });
    }
    this.sent.push(message);
    return Promise.resolve({ delivered: true, providerMessageId: `mem-${this.sent.length}` });
  }
}

/** The transport the configuration selects, or `undefined` for `none`. */
export const emailTransportFor = (
  environment: Pick<IdentityEnvironment, 'IDENTITY_EMAIL_TRANSPORT' | 'IDENTITY_EMAIL_OUTBOX_DIR'>,
): EmailTransport | undefined => {
  switch (environment.IDENTITY_EMAIL_TRANSPORT) {
    case 'outbox':
      return new OutboxEmailTransport(environment.IDENTITY_EMAIL_OUTBOX_DIR);
    default:
      return undefined;
  }
};

export class EmailDeliveryError extends Error {
  public constructor(
    public readonly transport: string,
    public readonly reason: string,
    public readonly attempts: number,
  ) {
    super(`email delivery failed via ${transport} after ${String(attempts)} attempt(s)`);
    this.name = 'EmailDeliveryError';
  }
}

/**
 * Send, with bounded retries for failures the transport calls retryable.
 *
 * Throws `EmailDeliveryError` when the message was not accepted. The error carries the transport's
 * coarse reason and never the message, so it is safe to log.
 */
export const sendEmail = async (
  transport: EmailTransport,
  message: NotificationMessage,
  options: { readonly maxAttempts?: number; readonly retryDelayMs?: number } = {},
): Promise<DeliveryResult> => {
  const maxAttempts = options.maxAttempts ?? 3;
  const retryDelay = options.retryDelayMs ?? 250;
  let last: DeliveryResult = { delivered: false, error: 'not attempted' };

  for (let attempt = 1; attempt <= maxAttempts; attempt += 1) {
    try {
      last = await transport.send(message);
    } catch (error) {
      last = { delivered: false, error: (error as Error).name, retryable: true };
    }
    if (last.delivered) return last;
    if (last.retryable !== true || attempt === maxAttempts) {
      throw new EmailDeliveryError(transport.name, last.error ?? 'unknown', attempt);
    }
    await new Promise((resolve) => setTimeout(resolve, retryDelay * 2 ** (attempt - 1)));
  }
  throw new EmailDeliveryError(transport.name, last.error ?? 'unknown', maxAttempts);
};
